-- 0003：快照 v2（M3 / T3.8）。
--
-- 0002 之后，快照能回答"回到这个时点需要哪些 git 事实"，但回答不了
-- "当时工作区里那些**没被 git 跟踪**的文件长什么样"——记录里只有路径清单。
-- 一旦有操作删掉了它们（reset --hard 之外的 clean / discard），路径就只是
-- 一份无法执行的通知。这两列把未跟踪内容也变成可回滚的东西：
--
--   manifest_json：内容备份的清单（JSON 数组）。每条含相对路径、字节数、
--     以及"是否来自 gitignore"标记。它是恢复未跟踪文件时**唯一**的来源——
--     没有清单就没有可复制的目标。空数组表示这份快照没有内容备份
--     （v1 记录、当时没有未跟踪文件、或体积超过上限时被整体跳过）。
--   backup_bytes：备份内容的字节总数。列表页与磁盘配额都读它，而不是
--     每次去扫备份目录：目录可能已经被清掉（配额、手动清理），
--     而这个数值仍然是"这份快照曾经占过多少"的历史事实。
--
-- 为什么还是 ALTER TABLE 而不是重建：与 0002 同样的理由——已有用户库里
-- 有真实快照，重建表意味着迁移代码要负责搬数据，多一份出错的可能而
-- 换不来任何好处。DEFAULT 0 让历史记录天然满足新约束（v1 没有备份）。
ALTER TABLE snapshots ADD COLUMN manifest_json TEXT;
ALTER TABLE snapshots ADD COLUMN backup_bytes INTEGER NOT NULL DEFAULT 0;
